#!/usr/bin/env python3
# generates docs/rosetta.md and docs/mk8.md
# from tests/cases.txt, asm/*.asm headers and build/results.json (make test / make docs)

import html
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.realpath(__file__)))
sys.path.insert(0, os.path.join(ROOT, 'tools'))
from run_tests import read_cases, MACHINES  # noqa: E402

def load_results():
    path = os.path.join(ROOT, 'build', 'results.json')
    if not os.path.exists(path):
        sys.exit('build/results.json not found - run `make test` first')
    return json.load(open(path))

def asm_header(asm_path):
    """REF url, title and the header comment block of an asm file"""
    lines = open(os.path.join(ROOT, asm_path)).read().split('\n')
    ref = None
    header = []
    for line in lines:
        if not line.startswith('#'): break
        header.append(line[2:].rstrip() if line.startswith('# ') else line[1:].rstrip())
        m = re.match(r'#\s*REF:\s*(\S+)', line)
        if m and ref is None: ref = m.group(1)
    title = ref.split('#')[0].rstrip('/').split('/wiki/')[-1].replace('_', ' ') if ref else None
    return ref, title, header

def asm_body(asm_path):
    """asm source without the leading comment block"""
    lines = open(os.path.join(ROOT, asm_path)).read().split('\n')
    i = 0
    while i < len(lines) and (lines[i].startswith('#') or not lines[i].strip()): i += 1
    return '\n'.join(lines[i:]).rstrip()

def fmt_cycles(n):
    if n is None: return '-'
    if n >= 1_000_000: return f'{n/1e6:.1f}M'
    if n >= 1_000: return f'{n/1e3:.1f}K'
    return str(n)

def short(xs, n=10):
    s = ' '.join(map(str, xs[:n]))
    return s + (' ...' if len(xs) > n else '')

GENERATED = '<!-- generated by tools/gen_docs.py (make docs) - do not edit by hand -->\n\n'

# === docs/rosetta.md =========================================================

def gen_rosetta(results):
    tasks = {}  # title -> {machine: result}
    order = []
    for r in results:
        ref, title, _ = asm_header(r['asm'])
        if not ref or 'rosettacode.org' not in ref: continue
        if title not in tasks:
            tasks[title] = dict(ref=ref.split('#')[0], machines={}, input=r['input'])
            order.append(title)
        prev = tasks[title]['machines'].get(r['machine'])
        # one case per machine, preferably with the same input as the first one
        if prev is None or (prev['input'] != tasks[title]['input'] and r['input'] == tasks[title]['input']):
            tasks[title]['machines'][r['machine']] = r
    count = {}
    for t in tasks.values():
        for m in t['machines']: count[m] = count.get(m, 0) + 1
    machines = sorted([m for m in count if count[m] >= 3], key=lambda m: int(m[2:]))
    others = sorted([m for m in count if count[m] < 3], key=lambda m: int(m[2:]))

    out = [GENERATED, '# Rosetta Code tasks in vimes2\n\n',
           'Simple [Rosetta Code](https://rosettacode.org) tasks rewritten for vimes2 machines. ',
           'Every program is also a test case (`tests/cases.txt`, expected output from `tests/oracle.py`), ',
           'so this page is regenerated from the passing test suite. ',
           'Numbers are 16-bit; tasks that need text print numbers instead (ie FizzBuzz: Fizz=-3, Buzz=-5, FizzBuzz=-15).\n\n',
           '**vm cycles** = executed VM instructions for the example input (identical on all variants of a machine). ',
           '**words** = program size in 16-bit words.\n\n']
    # summary table
    head = '| task | example input | output | ' + ' | '.join(f'{m} src | {m} cycles | {m} words' for m in machines) + ' |\n'
    out.append(head)
    out.append('|' + '---|' * (3 + 3 * len(machines)) + '\n')
    for title in order:
        t = tasks[title]
        any_r = next(iter(t['machines'].values()))
        row = [f"[{title}]({t['ref']})", f"`{any_r['input_label']}`", f"`{short(any_r['expected'])}`"]
        for m in machines:
            r = t['machines'].get(m)
            if r:
                name = os.path.basename(r['asm'])
                star = '' if r['input'] == t['input'] else '*'
                row += [f"[{name}](../{r['asm']})", fmt_cycles(r['cycles']) + star, str(r['code_words'])]
            else:
                row += ['-', '-', '-']
        out.append('| ' + ' | '.join(row) + ' |\n')
    out.append('\n`*` = different input than in the example column.')
    if others:
        out.append(f" Other machines with Rosetta programs: {', '.join(others)} (see `tests/cases.txt`).")
    out.append('\n')
    # side by side listings
    both = [t for t in order if len([m for m in tasks[t]['machines'] if m in machines]) > 1]
    if both:
        out.append('\n## Side by side\n\n')
        out.append(f"The same task on different machines ({', '.join(machines)}). ")
        out.append('mk8 is an accumulator machine without mul/div (HRM-like), mk13 is a memory-to-memory machine with `acc` for comparisons (smol-like).\n\n')
        for title in both:
            t = tasks[title]
            out.append(f"### [{title}]({t['ref']})\n\n")
            _, _, header = asm_header(next(iter(t['machines'].values()))['asm'])
            pseudo = [h for h in header if not h.startswith('REF')]
            while pseudo and not pseudo[0]: pseudo.pop(0)
            if pseudo:
                out.append('```\n' + '\n'.join(pseudo) + '\n```\n\n')
            ms = [m for m in machines if m in t['machines']]
            out.append('<table><tr>' + ''.join(f"<th>{m} ({fmt_cycles(t['machines'][m]['cycles'])} cycles, {t['machines'][m]['code_words']} words)</th>" for m in ms) + '</tr><tr>\n')
            for m in ms:
                r = t['machines'][m]
                body = html.escape(asm_body(r['asm']))
                out.append(f'<td valign="top"><pre>\n{body}\n</pre></td>\n')
            out.append('</tr></table>\n\n')
    return ''.join(out)

# === docs/mk8.md =============================================================

MK8_SEMANTICS = {
    'HLT':  ('0', 'halt the program'),
    'IN':   ('0', 'acc = read integer from stdin'),
    'OUT':  ('0', 'write acc to stdout'),
    'LDA':  ('a', 'acc = mem[a]'),
    'STA':  ('a', 'mem[a] = acc'),
    'ADD':  ('a', 'acc += mem[a]'),
    'SUB':  ('a', 'acc -= mem[a]'),
    'INC':  ('a', 'mem[a] += 1'),
    'DEC':  ('a', 'mem[a] -= 1'),
    'JMP':  ('a', 'jump to a'),
    'JZ':   ('a', 'jump to a if acc == 0'),
    'JN':   ('a', 'jump to a if acc < 0'),
    'LIT':  ('a', 'acc = a'),
    'CAL':  ('a', 'call subroutine at a (return address on the return stack)'),
    'RET':  ('0', 'return from subroutine'),
    'LPA':  ('a', 'acc = mem[mem[a]] (load via pointer)'),
    'SPA':  ('a', 'mem[mem[a]] = acc (store via pointer)'),
    'ASR':  ('a', 'acc >>= a (arithmetic shift right by a constant)'),
    'NOP':  ('a', 'do nothing (a can mark a label)'),
    'PUSH': ('a', 'mem[a] += 1; mem[mem[a]] = acc (a = stack pointer cell)'),
    'POP':  ('a', 'acc = mem[mem[a]]; mem[a] -= 1'),
    'JP':   ('a', 'jump to a if acc > 0'),
    'JZP':  ('a', 'jump to a if acc >= 0'),
    'JZN':  ('a', 'jump to a if acc <= 0'),
    'LPAO': ('a b', 'acc = mem[mem[a]+b] (Nim only, 3 words)'),
    'SPAO': ('a b', 'mem[mem[a]+b] = acc (Nim only, 3 words)'),
}

def gen_mk8(results):
    opc_text = open(os.path.join(ROOT, 'nim', 'mk8_opcodes.nim')).read()
    opcodes = re.findall(r'([A-Z][A-Z0-9_]*)\s*=\s*(\d+)', opc_text)
    c_names = set(re.findall(r'^\s*([A-Z][A-Z0-9_]*)\s*=\s*\d+', open(os.path.join(ROOT, 'c', 'mk8c.h')).read(), re.M))
    out = [GENERATED, '# mk8\n\n',
           'Accumulator machine inspired by [Human Resource Machine](https://store.steampowered.com/app/375820/Human_Resource_Machine/): ',
           '`mk7` extended with pointer access, subroutines and extra conditional jumps. ',
           'One register (`acc`), word-addressed memory (`mem`), a separate return stack and 16-bit words. ',
           'Every instruction is 2 words: `op a`.\n\n',
           '## How to think in mk8\n\n',
           '- Everything goes through `acc`: *load*, compute with memory cells, *store*. `load a sub b jn less` reads as "if a < b goto less".\n',
           '- Constants live in memory: programs start with `lit 0 to 0  lit 1 to 1`, so `add 1` means +1.\n',
           '- There is no mul/div: multiply by repeated addition, divide by repeated subtraction, halve with `asr 1`.\n',
           '- Recursion needs a manual data stack: `push s` / `pop s` (or the `push-s`/`pop-s` aliases) save locals around `cal`.\n',
           '- Aliases make it readable: `load=lda to=sta peek=lpa poke=spa call=cal`, variables as `n=2`.\n\n',
           '## Instruction set\n\n',
           '| opcode | # | args | semantics | C (c/ci/cd) |\n|---|---|---|---|---|\n']
    for name, num in opcodes:
        args, sem = MK8_SEMANTICS.get(name, ('?', '?'))
        out.append(f"| `{name}` | {num} | {args} | {sem} | {'yes' if name in c_names else 'no'} |\n")
    out += ['\n## Implementations\n\n',
            '| variant | file | dispatch |\n|---|---|---|\n',
            '| mk8c | [c/mk8c.c](../c/mk8c.c) | switch |\n',
            '| mk8ci | [c/mk8ci.c](../c/mk8ci.c) | token threading (`goto *labels[op]`, called "indirect" in README) |\n',
            '| mk8cd | [c/mk8cd.c](../c/mk8cd.c) | direct threading (code translated to label addresses) |\n',
            '| mk8 (Nim) | [nim/mk8.nim](../nim/mk8.nim) | case statement |\n\n',
            '```\nmake bin                                   # builds bin/mk8c bin/mk8ci bin/mk8cd (and bin/mk8_nim if nim is installed)\n',
            'python3 python/asm.py nim/mk8_opcodes.nim asm/gcd_mk8.asm -f b10 -o build/gcd.b10\n',
            'echo "1 48 18" | bin/mk8c build/gcd.b10           # -> 6\n',
            'echo "1 48 18" | bin/mk8c build/gcd.b10 -b 100    # benchmark: time and VM cycles on stderr\n```\n\n',
            '## Programs (all tested)\n\n',
            '| program | example input | output | vm cycles | words | variants |\n|---|---|---|---|---|---|\n']
    for r in results:
        if r['machine'] != 'mk8': continue
        name = os.path.basename(r['asm'])
        ref, title, _ = asm_header(r['asm'])
        label = f"[{name}](../{r['asm']})" + (f" ([{title}]({ref}))" if title else '')
        ok = [n for n, x in r['runs'].items() if x['ok']]
        out.append(f"| {label} | `{r['input_label']}` | `{short(r['expected'])}` | {fmt_cycles(r['cycles'])} | {r['code_words']} | {', '.join(ok)} |\n")
    return ''.join(out)

def main():
    results = load_results()
    os.makedirs(os.path.join(ROOT, 'docs'), exist_ok=True)
    for name, text in [('rosetta.md', gen_rosetta(results)), ('mk8.md', gen_mk8(results))]:
        with open(os.path.join(ROOT, 'docs', name), 'w') as f:
            f.write(text)
        print('written docs/' + name)

if __name__ == '__main__':
    main()
