#!/usr/bin/env python3
# generates:
#   js/opcodes.js    - opcode tables of all machines (from nim/mkN_opcodes.nim)
#   web/examples.js  - test cases with asm sources, inputs and expected outputs
#                      (so web/index.html works from file:// without fetch)
import glob, json, os, re, sys
ROOT = os.path.dirname(os.path.dirname(os.path.realpath(__file__)))
sys.path.insert(0, os.path.join(ROOT, 'tools'))
sys.path.insert(0, os.path.join(ROOT, 'python'))
from run_tests import read_cases, MACHINES  # noqa: E402
import oracle  # noqa: E402  (tests/ is on sys.path via run_tests)
import asm     # noqa: E402

HEADER = '// generated by tools/build_web.py (make web) - do not edit by hand\n'

def mk_num(name): return int(re.sub(r'\D', '', name))

def gen_opcodes():
    tables = {}
    for path in sorted(glob.glob(os.path.join(ROOT, 'nim', 'mk*_opcodes.nim')), key=lambda p: mk_num(os.path.basename(p))):
        name = os.path.basename(path).split('_')[0]
        tables[name] = asm.get_opcodes_from_text(open(path).read())
    js = [HEADER, '(function (root) {\n',
          '    const V = root.VIMES = root.VIMES || {}\n',
          '    V.opcodes = V.opcodes || {}\n']
    for name, t in tables.items():
        js.append(f'    V.opcodes.{name} = {json.dumps(t)}\n')
    js.append("    if (typeof module !== 'undefined' && module.exports) module.exports = V.opcodes\n")
    js.append("})(typeof window !== 'undefined' ? window : globalThis)\n")
    open(os.path.join(ROOT, 'js', 'opcodes.js'), 'w').write(''.join(js))
    return tables

def gen_examples():
    cases = read_cases(os.path.join(ROOT, 'tests', 'cases.txt'))
    sources = {}
    examples = []
    for c in cases:
        expected = oracle.ORACLES[c['oracle']]([int(t) for t in c['input'].split()])
        sources.setdefault(c['asm'], open(os.path.join(ROOT, c['asm'])).read())
        examples.append(dict(id=c['id'], machine=c['machine'], asm=c['asm'],
                             input=c['input'], input_label=c['input_label'], expected=expected))
    js = [HEADER, '(function (root) {\n',
          '    const V = root.VIMES = root.VIMES || {}\n',
          f'    V.sources = {json.dumps(sources, indent=1)}\n',
          f'    V.examples = {json.dumps(examples, indent=1)}\n',
          "    if (typeof module !== 'undefined' && module.exports) module.exports = { sources: V.sources, examples: V.examples }\n",
          "})(typeof window !== 'undefined' ? window : globalThis)\n"]
    open(os.path.join(ROOT, 'web', 'examples.js'), 'w').write(''.join(js))
    return examples

if __name__ == '__main__':
    t = gen_opcodes()
    e = gen_examples()
    print(f'written js/opcodes.js ({len(t)} machines) and web/examples.js ({len(e)} examples)')
